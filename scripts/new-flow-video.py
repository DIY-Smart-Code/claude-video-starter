#!/usr/bin/env python3
"""Start a new flow-explainer video from templates/flow-explainer.

Usage:
    python scripts/new-flow-video.py <slug> "Video title"

Copies the template (engine, tokens, fonts, GSAP, the demo scenes as a worked example) to videos/<slug>/,
sets meta.json and the backdrop seed, and prints the next steps. The demo's build/video_scenes.py,
script.txt and narration slots are then replaced by the /flow-explainer workflow.
Python 3.8+, standard library only.
"""
import json
import re
import shutil
import sys
from pathlib import Path

SKIP = {"qa", "storyboard", "snapshots", "out", "__pycache__", "renders",
        "compositions", "index.html", "ledger.json",          # generated by build.py
        "README.md", "DESIGN.md", "API.md"}                   # template docs stay in templates/flow-explainer/


def main() -> None:
    if len(sys.argv) < 2 or not re.fullmatch(r"[a-z0-9][a-z0-9-]*", sys.argv[1]):
        sys.exit(__doc__)
    slug = sys.argv[1]
    title = sys.argv[2] if len(sys.argv) > 2 else slug.replace("-", " ").capitalize()
    repo = Path(__file__).resolve().parent.parent
    src, dst = repo / "templates" / "flow-explainer", repo / "videos" / slug
    if dst.exists():
        sys.exit(f"{dst} already exists")
    shutil.copytree(src, dst, ignore=lambda d, names: [n for n in names if n in SKIP or n.endswith(".pyc")])
    for f in ("storyboard.html", "transcript.json", "narration.wav"):
        p = dst / f
        if p.exists():
            p.unlink()
    (dst / "meta.json").write_text(json.dumps({"id": slug, "name": title}, indent=2) + "\n", encoding="utf-8")
    vs = dst / "build" / "video_scenes.py"
    vs.write_text(vs.read_text(encoding="utf-8").replace('"seed": "flow-explainer-demo"', f'"seed": "{slug}"'), encoding="utf-8")
    print(f"created videos/{slug} from templates/flow-explainer (the demo scenes are the worked example)")
    print(f"next (from the repo root): BRIEF.md, SYSTEM.md, script.txt and build/video_scenes.py in videos/{slug}, then\n"
          f"  python videos/{slug}/build/build.py && python videos/{slug}/build/check_style.py && "
          f"python videos/{slug}/build/storyboard.py   (the full workflow: /flow-explainer)")


if __name__ == "__main__":
    main()
